describe('Renderer', () => {
  it('draws all active entities, effects, barrier, and fever telemetry', () => {
    const context = createMockContext();
    const renderer = new Renderer(context);
    const view = createSampleRenderView();

    renderer.render(view);

    expect(context.fillRect).toHaveBeenCalled();
    expect(context.strokeRect).toHaveBeenCalled();
    expect(context.fillText).toHaveBeenCalledWith('M', expect.any(Number), expect.any(Number));
    expect(context.fillText).toHaveBeenCalledWith('+250', 120, 85);
    expect(context.fillText).toHaveBeenCalledWith(
      'STAGE 1: NEON HORIZON',
      expect.any(Number),
      expect.any(Number),
    );
  });

  it('draws standard non-fever state without barrier or banner when inactive', () => {
    const context = createMockContext();
    const renderer = new Renderer(context);
    const baseView = createSampleRenderView({
      feverActive: false,
      barrierActive: false,
      stageBannerTimerSeconds: 0,
      combo: 1,
      paddle: {
        x: 190,
        y: 590,
        width: 84,
        baseWidth: 84,
        height: 14,
        velocityX: 0,
        speedPixelsPerSecond: 460,
        scaleX: 1,
        scaleY: 1,
        parryWindowRemainingSeconds: 0,
        parryCooldownRemainingSeconds: 0,
        parryCharged: false,
        wideRemainingSeconds: 0,
        laserRemainingSeconds: 0,
        laserCooldownRemainingSeconds: 0,
        magnetRemainingSeconds: 0,
      },
    });

    renderer.render(baseView);

    expect(context.fillText).toHaveBeenCalledWith(
      'PRISM CHARGE',
      expect.any(Number),
      expect.any(Number),
    );
  });
});
